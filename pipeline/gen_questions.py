PROMPT = ("你在为一个{who}学习的助手“{name}”准备训练数据。请写出孩子会对它说的话，类别：{cat}。\n"
          "要求：口语化，像这个年龄的真实孩子说话，长短不一（2到30个字），称呼它“{name}”或者不称呼都可以；每句都不一样；不要编号。"
          "这一批写 {n} 句，侧重：{focus}。只输出 JSON 数组，例如 [\"...\", \"...\"]。")


def job(cat, n, focus, who):
    # 类别名里的“小助手”换成当前人设的名字，只影响提示；输出里的 cat 保持原样
    p = PROMPT.format(who=who, name=persona.NAME, cat=cat.replace("小助手", persona.NAME), n=n, focus=focus)
    text, usage = llm_client.chat([{"role": "user", "content": p}], temperature=1.0, max_tokens=4000)
    m = re.search(r"\[.*\]", text, re.S)
    try:
        return cat, (json.loads(m.group(0)) if m else []), usage
    except ValueError:                                  # 偶尔一批格式坏了：丢掉这批
        return cat, [], usage


def main():
    out = sys.argv[1]
    band = int(os.environ.get("BAND", "1"))
    cats = CATS if band == 1 else CATS_BAND[band]
    c = persona.band_cfg(band)
    jobs = [(cat, 50, c["focus"][i % len(c["focus"])], c["who_long"]) for cat, total in cats.items() for i in range((total + 49) // 50)]
    old = json.load(open(sys.argv[2], encoding="utf-8")) if len(sys.argv) > 2 else []
    seen, rows, tok = {r["q"] for r in old}, list(old), 0
    with cf.ThreadPoolExecutor(int(os.environ.get("WORKERS", 8))) as ex:
        for cat, items, usage in ex.map(lambda a: job(*a), jobs):
            tok += usage.get("total_tokens", 0)
            for q in items:
                q = str(q).strip()
                if q and q not in seen and len(q) <= 40:
                    seen.add(q); rows.append({"cat": cat, "q": q})
    json.dump(rows, open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    print(f"{len(rows)} 句，用了 {tok} tokens（{len(jobs)} 次调用）")
    for cat, n in Counter(r["cat"] for r in rows).items():
        print(f"  {n:4d}  {cat[:30]}")


if __name__ == "__main__":
    main()
